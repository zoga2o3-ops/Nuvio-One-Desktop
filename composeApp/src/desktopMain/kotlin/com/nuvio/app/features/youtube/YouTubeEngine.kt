    private suspend fun feeds(
        continuationKey: String? = null,
        minItemsPerGroup: Int = 0,
        maxContinuePages: Int = 0,
        loader: () -> List<MediaGroup>?,
    ): List<YouTubeFeed> =
        withContext(Dispatchers.IO) {
            ensureInitialized()
            val groups = runCatching { loader() }.getOrNull().orEmpty()
            val finalGroups = ArrayList<MediaGroup>(groups.size)
            val result = groups.mapNotNull { group ->
                var feed = group.toFeed()
                var current = group
                var pages = 0
                while (feed.items.size < minItemsPerGroup && pages < maxContinuePages) {
                    val next = runCatching { manager.contentService.continueGroup(current) }.getOrNull()
                        ?: break
                    val nextFeed = next.toFeed()
                    if (nextFeed.items.isEmpty()) break
                    val merged = (feed.items + nextFeed.items)
                        .distinctBy { "${it.kind}:${it.videoId}" }
                    if (merged.size == feed.items.size) break
                    feed = feed.copy(items = merged)
                    current = next
                    pages += 1
                }
                finalGroups += current
                feed.takeIf { it.items.isNotEmpty() }
            }
            if (continuationKey != null) {
                if (finalGroups.isEmpty()) continuationGroups.remove(continuationKey)
                else continuationGroups[continuationKey] = finalGroups
            }
            result
        }

    private suspend fun singleFeed(
        continuationKey: String? = null,
        minItems: Int = 0,
        maxContinuePages: Int = 0,
        asChannels: Boolean = false,
        loader: () -> MediaGroup?,
    ): List<YouTubeFeed> =
        withContext(Dispatchers.IO) {
            ensureInitialized()
            val label = continuationKey ?: "feed"
            val group = runCatching { loader() }
                .onFailure { OneTubeDebugLog.line("$label failed: ${it.javaClass.simpleName}: ${it.message}") }
                .getOrNull() ?: run {
                OneTubeDebugLog.line("$label came back empty")
                if (continuationKey != null) continuationGroups.remove(continuationKey)
                return@withContext emptyList()
            }
            var feed = group.toFeed(asChannels)
            if (continuationKey == "channels") {
                OneTubeDebugLog.line("channels raw: ${group.mediaItems?.size ?: 0} items, ${feed.items.size} mapped")
                group.mediaItems.orEmpty().take(3).forEach { raw ->
                    OneTubeDebugLog.line("channel sample: type=${raw.type} channelId=${raw.channelId} reloadPageKey=${raw.reloadPageKey} videoId=${raw.videoId} playlistId=${raw.playlistId} title=${raw.title}")
                }
            }
            var current = group
            var pages = 0
            while (feed.items.size < minItems && pages < maxContinuePages) {
                val next = runCatching { manager.contentService.continueGroup(current) }.getOrNull()
                    ?: break
                val nextFeed = next.toFeed(asChannels)
                if (nextFeed.items.isEmpty()) break
                val merged = (feed.items + nextFeed.items)
                    .distinctBy { "${it.kind}:${it.videoId}" }
                if (merged.size == feed.items.size) break
                feed = feed.copy(items = merged)
                current = next
                pages += 1
            }
            if (continuationKey != null) {
                if (feed.items.isEmpty()) continuationGroups.remove(continuationKey)
                else continuationGroups[continuationKey] = mutableListOf(current)
            }
            feed.takeIf { it.items.isNotEmpty() }?.let(::listOf).orEmpty()
        }

    suspend fun continueFeed(key: String): List<YouTubeFeed> = withContext(Dispatchers.IO) {
        ensureInitialized()
        val groups = continuationGroups[key] ?: return@withContext emptyList()
        val additions = mutableListOf<YouTubeFeed>()
        groups.forEachIndexed { index, group ->
            val next = runCatching { manager.contentService.continueGroup(group) }.getOrNull()
                ?: return@forEachIndexed
