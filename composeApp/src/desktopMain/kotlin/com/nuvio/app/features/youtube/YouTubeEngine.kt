/**
 * Thin desktop-side facade over the ported SmartTube engine.
 *
 * All engine calls are blocking, so they are pushed onto [Dispatchers.IO].
 */
internal object YouTubeEngine {
    private val initLock = Mutex()
    private var initialized = false
    private val continuationGroups = java.util.concurrent.ConcurrentHashMap<String, MutableList<MediaGroup>>()

    private suspend fun ensureInitialized() {
        if (initialized) return
        initLock.withLock {
            if (initialized) return
            EnginePlatform.configure(
                DesktopStorage.rootDir.resolve("youtube-engine"),
                DesktopStorage.cacheDir.resolve("youtube-engine"),
            )
            if (DesktopHostOs.current == DesktopHostOs.WINDOWS) {
                PoTokenRuntime.hostFactory = { WebView2PoTokenJsRuntime() }
            }
            GlobalPreferences.instance(EngineContext.get())
            // The engine restores the saved YouTube sign-in on a background thread. Restore it
            // here, before the first sign-in check, so OneTube doesn't ask to sign in on every launch.
            com.liskovsoft.googleapi.oauth2.manager.OAuth2AccountManager.instance().init()
            // libmpv consumes WebVTT directly; YouTube's timedtext endpoint can
            // return VTT instead of TTML when this is set.
            selectedCaptionFormat = CaptionFormat.VTT
            initialized = true
        }
    }

