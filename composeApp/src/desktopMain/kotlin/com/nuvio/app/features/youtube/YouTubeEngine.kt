    private fun MediaItem.toVideoItem(asChannels: Boolean = false): YouTubeVideoItem? {
        // The Channels grid: YouTube gives each subscribed channel only a browse key, with no channel or video id.
        if (asChannels && channelId == null && videoId == null && playlistId == null) {
            val key = reloadPageKey ?: return null
            return YouTubeVideoItem(
                videoId = key,
                title = title ?: "Channel",
                // The card's round badge shows the first letter of the author, so the channel name goes here too.
                author = title ?: "Channel",
                thumbnailUrl = cardImageUrl,
                durationMs = 0L,
                isLive = false,
                kind = YouTubeItemKind.CHANNEL,
                reloadPageKey = key,
                sourceItem = this,
            )
        }
        val kind = when (type) {
            MediaItem.TYPE_CHANNEL -> YouTubeItemKind.CHANNEL
            MediaItem.TYPE_PLAYLIST -> YouTubeItemKind.PLAYLIST
            else -> YouTubeItemKind.VIDEO
        }
        val id = when (kind) {
            YouTubeItemKind.CHANNEL -> channelId ?: reloadPageKey ?: return null
            YouTubeItemKind.PLAYLIST -> playlistId ?: reloadPageKey ?: videoId ?: return null
            YouTubeItemKind.VIDEO -> videoId ?: return null
        }
        return YouTubeVideoItem(
            videoId = id,
            title = title ?: id,
            author = author ?: secondTitle?.toString(),
            thumbnailUrl = cardImageUrl,
            durationMs = durationMs,
            isLive = isLive,
            kind = kind,
            channelId = channelId,
            playlistId = playlistId,
            reloadPageKey = reloadPageKey,
            startTimeSeconds = startTimeSeconds,
            percentWatched = percentWatched,
            sourceItem = this,
            metadata = secondTitle?.toString()?.takeIf { it.isNotBlank() },
            badgeText = badgeText?.takeIf { it.isNotBlank() },
            previewUrl = videoPreviewUrl?.takeIf { it.isNotBlank() },
            isShorts = isShorts(),
            isMusic = type == MediaItem.TYPE_MUSIC,
        )
    }
