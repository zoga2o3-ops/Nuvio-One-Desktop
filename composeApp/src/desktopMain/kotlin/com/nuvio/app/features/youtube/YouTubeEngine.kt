    /**
     * Loads a playlist including its continuation pages (the plain [playlist]
     * call returns only the first page). [complete] is false when [maxPages]
     * stopped the load before the end.
     */
    data class FullPlaylist(val items: List<YouTubeVideoItem>, val complete: Boolean)

    suspend fun playlistAll(
        playlistId: String,
        maxPages: Int = 60,
        onProgress: (FullPlaylist) -> Unit = {},
    ): FullPlaylist =
        loadAll(maxPages, onProgress) { manager.contentService.getPlaylist(playlistId) }

    /**
     * Same as [playlistAll] for a playlist row. Some account rows (Watch later,
     * Liked videos, some saved lists) carry a page key instead of a playlist id
     * and only open through [group]; try whichever the row has.
     */
    suspend fun playlistAll(
        item: YouTubeVideoItem,
        maxPages: Int = 60,
        onProgress: (FullPlaylist) -> Unit = {},
    ): FullPlaylist {
        val byId = item.playlistId?.takeIf { it.isNotBlank() }?.let { playlistAll(it, maxPages, onProgress) }
        if (byId != null && byId.items.isNotEmpty()) return byId
        val byKey = item.reloadPageKey?.takeIf { it.isNotBlank() }
            ?.let { key -> loadAll(maxPages, onProgress) { manager.contentService.getGroup(key) } }
        if (byKey != null && byKey.items.isNotEmpty()) return byKey
        return byId ?: byKey ?: playlistAll(item.videoId, maxPages, onProgress)
    }

