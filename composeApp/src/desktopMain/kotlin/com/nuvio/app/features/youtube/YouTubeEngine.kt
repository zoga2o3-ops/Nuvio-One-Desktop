/**
 * Adaptive YouTube streams are decoded by mpv. 1080p H.264 starts much faster
 * than 4K AV1 on typical Windows GPUs and avoids software-decoding stalls.
 */
/** Downloads the first megabyte of a stream and returns the speed in KB/s (diagnostic, -1 on failure). */
private fun measureKbps(url: String): Long = runCatching {
    val connection = java.net.URL(url).openConnection() as java.net.HttpURLConnection
    connection.setRequestProperty("Range", "bytes=0-1048575")
    connection.setRequestProperty("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64)")
    connection.connectTimeout = 10_000
    connection.readTimeout = 20_000
    val start = System.nanoTime()
    var total = 0L
    connection.inputStream.use { input ->
        val buffer = ByteArray(65_536)
        while (true) {
            val read = input.read(buffer)
            if (read < 0) break
            total += read
        }
    }
    connection.disconnect()
    val ms = (System.nanoTime() - start) / 1_000_000L
    if (ms <= 0L) 0L else total * 1000L / ms / 1024L
}.getOrDefault(-1L)

/** Asks YouTube not to throttle a plain stream URL (the throttle is what stalls longer videos). */
private fun unthrottled(url: String): String =
    if (url.contains("ratebypass=")) url else url + (if (url.contains("?")) "&" else "?") + "ratebypass=yes"

private const val MAX_YOUTUBE_VIDEO_DIMENSION = 1920
private const val MAX_YOUTUBE_VIDEO_HEIGHT = 1080

private fun videoCodecRank(mimeType: String?): Int {
    val mime = mimeType?.lowercase() ?: return 0
    return when {
        "avc1" in mime -> 3
        "vp9" in mime || "vp09" in mime -> 2
        "av01" in mime -> 1
        else -> 0
    }
}

private fun audioCodecRank(mimeType: String?): Int {
    val mime = mimeType?.lowercase() ?: return 0
    return when {
        "mp4a" in mime -> 2
        "opus" in mime -> 1
        else -> 0
    }
}

private fun isOriginalAudio(format: MediaFormat): Boolean {
    val trackId = format.audioTrackId
    if (!trackId.isNullOrBlank()) return trackId.endsWith(".4")
    val language = format.language
    if (language.isNullOrBlank()) return true
    return language.contains("(original)", ignoreCase = true)
}





