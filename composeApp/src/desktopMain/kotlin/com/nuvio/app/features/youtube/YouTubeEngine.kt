    suspend fun resolvePlayback(
        item: YouTubeVideoItem,
        music: Boolean,
        maxHeight: Int? = null,
        maxAudioKbps: Int? = null,
    ): YouTubePlayback =
        withContext(Dispatchers.IO) {
            ensureInitialized()
            val info = manager.mediaItemService.getFormatInfo(item.videoId)
                ?: error("Could not load video info.")

            if (info.isUnplayable) {
                error(info.playabilityReason ?: "This video is unavailable.")
            }

            val adaptive = info.adaptiveFormats.orEmpty()
            val allAudioCandidates = adaptive
                .filter { it.mimeType?.startsWith("audio/") == true && !it.isDrc }
                .filter { !it.url.isNullOrBlank() }
            val cappedAudio = maxAudioKbps?.let { kbps ->
                allAudioCandidates.filter { (it.bitrate?.toLongOrNull() ?: 0L) <= kbps * 1000L }
            }.orEmpty()
            val audioCandidates = cappedAudio.ifEmpty { allAudioCandidates }
            val audio = audioCandidates.maxWithOrNull(
                compareBy<MediaFormat>(
                    { if (isOriginalAudio(it)) 1 else 0 },
                    { audioCodecRank(it.mimeType) },
                    { it.bitrate?.toLongOrNull() ?: 0L },
                ),
            )
            val audioTracks = audioCandidates
                .groupBy { it.audioTrackId ?: it.language ?: it.url }
                .values
                .mapNotNull { formats ->
                    val best = formats.maxWithOrNull(
                        compareBy<MediaFormat>(
                            { audioCodecRank(it.mimeType) },
                            { it.bitrate?.toLongOrNull() ?: 0L },
                        ),
                    ) ?: return@mapNotNull null
                    val url = best.url ?: return@mapNotNull null
                    YouTubeAudioTrack(
                        url = unthrottled(url),
                        label = best.language ?: "Audio",
                        language = best.language,
                        isOriginal = isOriginalAudio(best),
                    )
                }
                .sortedWith(compareByDescending<YouTubeAudioTrack> { it.isOriginal }.thenBy { it.label })
            val videoCandidates = adaptive
                .filter { it.mimeType?.startsWith("video/") == true && !it.isDrc && !it.isOtf }
                .filter { !it.url.isNullOrBlank() }
            val availableVideoHeights = videoCandidates
                .mapNotNull { it.height.takeIf { height -> height in 1..MAX_YOUTUBE_VIDEO_HEIGHT } }
                .distinct()
                .sortedDescending()
            val cappedVideoCandidates = videoCandidates
                .filter { it.width in 0..MAX_YOUTUBE_VIDEO_DIMENSION && it.height in 0..MAX_YOUTUBE_VIDEO_DIMENSION }
                .filter { maxHeight == null || it.height <= maxHeight }
                .ifEmpty { videoCandidates }
            val video = cappedVideoCandidates.maxWithOrNull(
                compareBy<MediaFormat>(
                    { it.height },
                    { videoCodecRank(it.mimeType) },
                    { it.bitrate?.toLongOrNull() ?: 0L },
                ),
            )
            OneTubeDebugLog.line("formats client=${info.clientInfo?.clientName} pot=${!info.poToken.isNullOrBlank()} sabr=${!info.serverAbrStreamingUrl.isNullOrBlank()} adaptive=${adaptive.size} urlFormats=${info.urlFormats.orEmpty().size} hls=${!info.hlsManifestUrl.isNullOrBlank()}")
            video?.let { v -> val u = v.url.orEmpty(); OneTubeDebugLog.line("video height=${v.height} mime=${v.mimeType?.take(30)} bitrate=${v.bitrate} n=${u.contains("&n=") || u.contains("?n=")} ratebypass=${u.contains("ratebypass=yes")}") }
            val regular = info.urlFormats.orEmpty()
                .filter { !it.url.isNullOrBlank() }
                .filter { it.width in 0..MAX_YOUTUBE_VIDEO_DIMENSION && it.height in 0..MAX_YOUTUBE_VIDEO_DIMENSION }
                .maxWithOrNull(
                    compareBy<MediaFormat>(
                        { it.height },
                        { videoCodecRank(it.mimeType) },
                    ),
                )
            val hls = info.hlsManifestUrl

            val title = info.title ?: item.title
            val author = info.author ?: item.author
            val userAgent = info.clientInfo?.userAgent
                ?: "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
                "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
            val headers = mapOf(
                "User-Agent" to userAgent,
                "Referer" to "https://www.youtube.com/",
            )
            val subtitles = info.subtitles.orEmpty().mapNotNull { subtitle ->
                val url = subtitle.baseUrl ?: return@mapNotNull null
                YouTubeSubtitle(
                    url = url,
                    language = subtitle.languageCode ?: "und",
                    name = subtitle.name,
                    vssId = subtitle.vssId,
                    isAutoGenerated = subtitle.type == "asr",
                    translatable = runCatching { subtitle.isTranslatable }.getOrDefault(false),
                )
            }

            val videoOut = video?.url?.let(::unthrottled)
            val audioOut = audio?.url?.let(::unthrottled)
            OneTubeDebugLog.line("final video ratebypass=${videoOut?.contains("ratebypass=yes") == true} audio ratebypass=${audioOut?.contains("ratebypass=yes") == true}")
            videoOut?.let { OneTubeDebugLog.line("server speed video ${measureKbps(it)} KB/s") }
            when {
                music && audio != null && !audio.url.isNullOrBlank() ->
                    YouTubePlayback(unthrottled(audio.url!!), null, title, author, headers, subtitles, audioTracks)

                video != null && audio != null && !video.url.isNullOrBlank() ->
                    YouTubePlayback(
                        unthrottled(video.url!!),
                        audio.url?.let(::unthrottled),
                        title,
                        author,
                        headers,
                        subtitles,
                        audioTracks,
                        availableVideoHeights,
                    )

                hls != null -> YouTubePlayback(hls, null, title, author, headers, subtitles)

                regular != null && !regular.url.isNullOrBlank() ->
                    YouTubePlayback(regular.url!!, null, title, author, headers, subtitles)

                audio != null && !audio.url.isNullOrBlank() ->
                    YouTubePlayback(audio.url!!, null, title, author, headers, subtitles)

                else -> error("No playable formats were returned.")
            }
        }

