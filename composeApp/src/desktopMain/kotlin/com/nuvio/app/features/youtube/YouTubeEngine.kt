    suspend fun search(query: String): List<YouTubeVideoItem> = search(query, 0)

    suspend fun search(query: String, options: Int): List<YouTubeVideoItem> = withContext(Dispatchers.IO) {
        ensureInitialized()
        val groups = if (options == 0) {
            manager.contentService.getSearch(query)
        } else {
            manager.contentService.getSearch(query, options)
        }.orEmpty()
        groups.asSequence()
            .flatMap { group -> (group.mediaItems ?: emptyList()).asSequence() }
            .mapNotNull { it.toVideoItem() }
            .distinctBy { it.videoId }
            .toList()
    }

    /**
     * Search results across several pages: the first page, then YouTube's continuations, up to [maxPages].
     * [search] only returns the first page, which is about 16 results.
     */
    suspend fun searchPaged(query: String, options: Int, maxPages: Int = 12, maxItems: Int = 150): List<YouTubeVideoItem> = withContext(Dispatchers.IO) {
        ensureInitialized()
        val first = (if (options == 0) manager.contentService.getSearch(query) else manager.contentService.getSearch(query, options)).orEmpty()
        val groups = first.toMutableList()
        var last: MediaGroup? = first.lastOrNull { it.mediaItems?.isNotEmpty() == true }
        var pages = 1
        while (last != null && pages < maxPages && groups.sumOf { it.mediaItems?.size ?: 0 } < maxItems) {
            val current: MediaGroup = last
            val next = runCatching { manager.contentService.continueGroup(current) }.getOrNull() ?: break
            if (next.mediaItems.isNullOrEmpty()) break
            groups += next
            last = next
            pages += 1
        }
        groups.asSequence()
            .flatMap { group -> (group.mediaItems ?: emptyList()).asSequence() }
            .mapNotNull { it.toVideoItem() }
            .distinctBy { it.videoId }
            .toList()
    }

