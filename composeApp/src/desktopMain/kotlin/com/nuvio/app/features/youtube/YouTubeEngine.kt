    suspend fun music(): List<YouTubeFeed> {
        val primary = feeds(continuationKey = "music", minItemsPerGroup = 16, maxContinuePages = 1) {
            manager.contentService.getMusicObserve().blockingFirst()
        }
        val musicOnly = primary.mapNotNull { feed ->
            val items = feed.items.filter { it.isMusic }
            if (items.isEmpty()) null else feed.copy(items = items)
        }
        if (musicOnly.sumOf { it.items.size } >= 8) return musicOnly

        val fallback = runCatching {
            search("music", SearchOptions.TYPE_VIDEO)
                .map { it.copy(isMusic = true) }
                .distinctBy { it.videoId }
        }.getOrDefault(emptyList())
        return if (fallback.isNotEmpty()) {
            continuationGroups.remove("music")
            listOf(YouTubeFeed("Music", fallback))
        } else {
            musicOnly
        }
    }

