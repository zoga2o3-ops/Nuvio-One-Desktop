    private suspend fun loadAll(
        maxPages: Int,
        onProgress: (FullPlaylist) -> Unit,
        first: () -> MediaGroup?,
    ): FullPlaylist = withContext(Dispatchers.IO) {
        ensureInitialized()
        var current = runCatching { first() }.getOrNull()
            ?: return@withContext FullPlaylist(emptyList(), complete = true)
        var items = current.toFeed().items
        // Report each page as it arrives, so a long playlist shows its first songs straight away.
        if (items.isNotEmpty()) onProgress(FullPlaylist(items, complete = false))
        var pages = 0
        var complete = true
        var pagesWithoutNewItems = 0
        // Follow continuation tokens to the end. A page can fail transiently or
        // come back empty (removed/private videos) mid-playlist, so retry failed
        // pages and keep going while YouTube still hands out a new token.
        while (true) {
            if (pages >= maxPages) { complete = false; break }
            // A track the user picked goes first; the next page waits for it.
            MusicStreamResolver.waitForTrackLookups()
            var next: MediaGroup? = null
            for (attempt in 0 until 3) {
                next = runCatching { manager.contentService.continueGroup(current) }.getOrNull()
                if (next != null) break
                kotlinx.coroutines.delay(500L * (attempt + 1))
            }
            if (next == null) break
            pages += 1
            val merged = (items + next.toFeed().items).distinctBy { "${it.kind}:${it.videoId}" }
            pagesWithoutNewItems = if (merged.size > items.size) 0 else pagesWithoutNewItems + 1
            items = merged
            onProgress(FullPlaylist(items, complete = false))
            val token = next.nextPageKey
            val stuck = !token.isNullOrBlank() && token == current.nextPageKey
            current = next
            if (stuck || pagesWithoutNewItems >= 3) break
        }
        FullPlaylist(items, complete)
    }

